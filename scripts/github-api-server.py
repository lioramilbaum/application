#!/usr/bin/env python3
"""Emulates the GitHub REST endpoints that OCM's GitHub/v1 access uses.

The OCM client treats a non-github.com repoUrl as GitHub Enterprise and calls
{host}/api/v3/. It resolves a ref with GET .../commits/{ref} (raw SHA when the
Accept header asks for application/vnd.github.v3.sha), gets a 302 from
GET .../tarball/{sha}, and then downloads the archive from the Location.

Archives are built in memory with fixed metadata so the same tree always gives
the same bytes. The tree for a commit is {commits-dir}/{sha}/ when that directory
exists, otherwise {commits-dir} itself.
"""

import argparse
import gzip
import io
import json
import os
import re
import sys
import tarfile
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import unquote

SHA_RE = re.compile(r"^[0-9a-f]{40}$")
SHA_MEDIA_TYPE = "application/vnd.github.v3.sha"
COMMITS_RE = re.compile(r"^/api/v3/repos/([^/]+)/([^/]+)/commits/(.+)$")
TARBALL_RE = re.compile(r"^/api/v3/repos/([^/]+)/([^/]+)/tarball/(.+)$")
CODELOAD_RE = re.compile(r"^/_codeload/([^/]+)/([^/]+)/([0-9a-f]{40})\.tar\.gz$")
REGENERATED_NAME = "REGENERATED"


def tree_for(commits_dir, sha):
    candidate = os.path.join(commits_dir, sha)
    return candidate if os.path.isdir(candidate) else commits_dir


def build_archive(tree, prefix, extra_entry=False):
    entries = [(prefix.rstrip("/"), None)]
    for root, dirs, files in os.walk(tree):
        dirs.sort()
        for name in files:
            path = os.path.join(root, name)
            rel = os.path.relpath(path, tree).replace(os.sep, "/")
            with open(path, "rb") as f:
                entries.append((prefix + rel, f.read()))
    if extra_entry:
        entries.append((prefix + REGENERATED_NAME, b"regenerated by the emulator\n"))
    entries.sort(key=lambda entry: entry[0])

    tar_buf = io.BytesIO()
    with tarfile.open(fileobj=tar_buf, mode="w", format=tarfile.PAX_FORMAT) as tar:
        for name, data in entries:
            info = tarfile.TarInfo(name)
            info.mtime = 0
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            if data is None:
                info.type = tarfile.DIRTYPE
                info.mode = 0o755
                tar.addfile(info)
            else:
                info.size = len(data)
                info.mode = 0o644
                tar.addfile(info, io.BytesIO(data))

    gz_buf = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=gz_buf, mtime=0) as gz:
        gz.write(tar_buf.getvalue())
    return gz_buf.getvalue()


def read_refs(path):
    refs = {}
    try:
        with open(path) as f:
            for line in f:
                parts = line.split()
                if len(parts) == 2:
                    refs[parts[0]] = parts[1]
    except FileNotFoundError:
        pass
    return refs


class Server(ThreadingHTTPServer):
    daemon_threads = True

    def __init__(self, address, args):
        super().__init__(address, Handler)
        self.refs_file = args.refs_file
        self.commits_dir = args.commits_dir
        self.owner = args.owner
        self.repo = args.repo
        self.rewrite_sha = args.rewrite_sha
        self.log_path = args.log
        self.requests = []
        self.lock = threading.Lock()

    def record(self, method, path):
        stamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        with self.lock:
            self.requests.append({"method": method, "path": path, "time": stamp})
            if self.log_path:
                with open(self.log_path, "a") as f:
                    f.write(f"{stamp} {method} {path}\n")

    def resolve(self, ref):
        if SHA_RE.match(ref):
            return ref
        refs = read_refs(self.refs_file)
        return refs.get(ref) or refs.get("refs/heads/" + ref)


class Handler(BaseHTTPRequestHandler):
    server_version = "github-api-emulator"

    def log_message(self, fmt, *args):
        pass

    def _send(self, status, body=b"", content_type="application/json", headers=None):
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        for name, value in (headers or {}).items():
            self.send_header(name, value)
        self.end_headers()
        self.wfile.write(body)

    def _json(self, status, obj):
        self._send(status, json.dumps(obj).encode())

    def _not_found(self):
        self._json(404, {"message": "Not Found"})

    def _is_repo(self, owner, repo):
        return owner == self.server.owner and repo == self.server.repo

    def do_GET(self):
        path = self.path.split("?", 1)[0]
        self.server.record("GET", path)

        if path == "/-/ready":
            return self._send(200, b"ok\n", "text/plain")
        if path == "/-/log":
            return self._json(200, self.server.requests)

        match = COMMITS_RE.match(path)
        if match:
            owner, repo, ref = match.groups()
            sha = self.server.resolve(unquote(ref)) if self._is_repo(owner, repo) else None
            if sha is None:
                return self._not_found()
            if SHA_MEDIA_TYPE in self.headers.get("Accept", ""):
                return self._send(200, sha.encode(), "application/vnd.github.v3.sha")
            return self._json(200, {"sha": sha})

        match = TARBALL_RE.match(path)
        if match:
            owner, repo, ref = match.groups()
            sha = self.server.resolve(unquote(ref)) if self._is_repo(owner, repo) else None
            if sha is None:
                return self._not_found()
            location = f"http://{self.headers.get('Host')}/_codeload/{owner}/{repo}/{sha}.tar.gz"
            return self._send(302, headers={"Location": location})

        match = CODELOAD_RE.match(path)
        if match:
            owner, repo, sha = match.groups()
            if not self._is_repo(owner, repo):
                return self._not_found()
            prefix = f"{owner}-{repo}-{sha[:7]}/"
            archive = build_archive(
                tree_for(self.server.commits_dir, sha),
                prefix,
                extra_entry=(sha == self.server.rewrite_sha),
            )
            return self._send(200, archive, "application/x-gzip")

        return self._not_found()


def write_archive(args):
    prefix = f"{args.owner}-{args.repo}-{args.sha[:7]}/"
    data = build_archive(tree_for(args.commits_dir, args.sha), prefix)
    with open(args.out, "wb") as f:
        f.write(data)


def parse_args(argv):
    p = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    p.add_argument("--mode", choices=["server", "archive"], default="server")
    p.add_argument("--port", type=int)
    p.add_argument("--refs-file")
    p.add_argument("--commits-dir", required=True)
    p.add_argument("--owner", required=True)
    p.add_argument("--repo", required=True)
    p.add_argument("--log")
    p.add_argument("--rewrite-sha")
    p.add_argument("--sha")
    p.add_argument("--out")
    args = p.parse_args(argv)
    if args.mode == "server" and (args.port is None or args.refs_file is None):
        p.error("server mode needs --port and --refs-file")
    if args.mode == "archive" and (not args.sha or not args.out):
        p.error("archive mode needs --sha and --out")
    return args


def main(argv=None):
    args = parse_args(argv)
    if args.mode == "archive":
        write_archive(args)
        return 0
    try:
        server = Server(("127.0.0.1", args.port), args)
    except OSError as err:
        print(f"cannot bind to port {args.port}: {err}", file=sys.stderr)
        return 1
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
